DIRECTOR_HISTORY_BLOCK = (
    "【关于历史往来的定义和规则】\n"
    "\n"
    "以下内容均为已经发生过的历史往来，不是当前正在发生的消息。\n"
    "\n"
    "- 这些内容只作为背景信息，不构成我这一轮必须回复的消息。\n"
    "- 我已经知道这些内容，不得把其中任何一句重新当作“刚刚收到的新消息”。\n"
    "- 历史往来发生在当前这一轮之前；期间可能已经经过较长时间，"
    "我也可能已经做过其他事情、去过其他地方。\n"
    "- 我不得仅因为历史对话尚未形成完整结局，就默认这一轮必须继续回复。\n"
    "- 只有当历史对话中存在尚未结束的事项，且当前仍有实际的新变化、"
    "明确意图或需要处理的后续时，我才可以继续围绕它行动。\n"
    "- 如果历史对话没有产生当前需要处理的新事项，"
    "我这一轮的行为、想法和回复与该历史往来无关。\n"
    "- 我不得为了产生回复，强行从历史对话中寻找一个“还可以继续说”的话题。\n"
    "- 历史内容只能提供已经发生过的事实，"
    "不得据此虚构当前时间、地点、情绪、意图或新事件。\n"
    "\n"


    "【往来记录】\n"
    "{lines}"
)


def director_history_block(lines: str) -> str:
    if not (lines or "").strip():
        return ""
    return DIRECTOR_HISTORY_BLOCK.replace("{lines}", lines.strip())


def director_phase_block(phase: str) -> str:
    if phase == "advance":
        return DIRECTOR_ADVANCE_BLOCK + "\n\n" + DIRECTOR_AUDIENCE_BLOCK
    return ""


